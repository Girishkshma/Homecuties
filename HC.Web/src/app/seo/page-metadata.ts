import { environment } from '../../environments/environment';
import { Product } from '../models/product.model';
import { productImageUrl } from '../models/product-image';

/**
 * What the page head says about the storefront, kept as plain functions so the rules can be tested without a browser
 * and read without reading the service that writes them into the document (see SeoService and PageTitleStrategy).
 *
 * Two rules run through everything here:
 *
 * - Search engines are given ABSOLUTE urls. A canonical, an og:url or an og:image that is a bare path is a value a
 *   crawler has to guess the host for, and the storefront is served from inside a Node process that is told the host
 *   per request - so the host comes from `environment.siteUrl` rather than from window.location, which does not exist
 *   while the page is rendered on the server.
 * - A title or a description is never invented for a page that does not know what it is showing. A product page that
 *   has not loaded its product yet says what the shop is; it is corrected the moment the product arrives.
 */

/** The shop's name, as a browser tab, a search result and a share card write it. */
export const BRAND_NAME = 'Homecuties';

/** The storefront's own address, without a trailing slash (see environment.siteUrl). */
export const SITE_URL = environment.siteUrl.replace(/\/+$/, '');

/**
 * What the shop is, said for the whole storefront: the shell's description, and the description of any page that has
 * nothing of its own to say.
 */
export const DEFAULT_DESCRIPTION =
  'Handcrafted home decor from Homecuties: Channapatna wooden toys, painted pots and bottle vases, each made by hand and delivered across India.';

/** The terms the storefront is worth finding for. Not a ranking factor, but read by some directories and engines. */
export const DEFAULT_KEYWORDS = [
  'handcrafted home decor',
  'Channapatna toys',
  'wooden toys',
  'painted pots',
  'bottle vases',
  'home decor online',
  'home accessories'
];

/**
 * The card a shared link draws when the page has no picture of its own: the logo lockup on white, generated by
 * scripts/generate-icons.ps1 and served from the root of the site.
 */
export const SHARE_IMAGE_PATH = '/og-image.png';
export const SHARE_IMAGE_WIDTH = 1200;
export const SHARE_IMAGE_HEIGHT = 630;

/**
 * The longest description a result shows before it is cut off - roughly 160 characters, and the width a share card
 * draws. Descriptions are trimmed to it rather than left to the engine: what is cut, and where, is then the shop's
 * choice and not a search engine's.
 */
export const DESCRIPTION_LIMIT = 160;

/**
 * What a crawler is told about a page anyone may open: index it, follow the links in it, and show a product photo at
 * full size in the result (max-image-preview) rather than as a thumbnail.
 */
export const INDEXABLE_ROBOTS = 'index, follow, max-image-preview:large, max-snippet:-1, max-video-preview:-1';

/**
 * What a crawler is told about a page that is only ever about one shopper - a cart, an order, a form behind a
 * sign-in. It is not blocked in robots.txt on purpose: a blocked page is never fetched, so the 'noindex' in its head
 * would never be read, and the address could still be listed with no description at all.
 */
export const NOINDEX_ROBOTS = 'noindex, follow';

/** Where a page lives, and what it says about itself. */
export interface PageMetadata {
  /** The page's own title, without the brand: 'Channapatna Wooden Toys' is written as that plus ' | Homecuties'. */
  title: string;
  description?: string;
  /** The path the page is canonicalised to, with no query string or hash ('/shop/12'). Defaults to '/'. */
  path?: string;
  keywords?: string[];
  /** Absolute url of the picture a share card draws. Defaults to the generated share card. */
  image?: string;
  /** What the share card's picture shows. Defaults to the page title. */
  imageAlt?: string;
  /** Open Graph type. 'product' on a product page. */
  type?: 'website' | 'product' | 'article';
  /** True for the pages that are only about one shopper: no canonical, and 'noindex' in the head. */
  noindex?: boolean;
}

/** An absolute address on the storefront's own host, for a path that may be absolute already. */
export function absoluteUrl(path: string): string {
  if (/^https?:\/\//i.test(path)) {
    return path;
  }

  const withoutHash = (path || '/').split('#')[0];

  return `${SITE_URL}${withoutHash.startsWith('/') ? withoutHash : `/${withoutHash}`}`;
}

/**
 * The page a url names, with the query string and the hash taken off and one leading slash: a router url ('/shop/12')
 * to a canonical path. The shop's search sets '?q=', and a search result must not be canonicalised to itself - two
 * shoppers' searches are not two pages.
 */
export function pagePath(url: string | null | undefined): string {
  const path = (url || '').split('?')[0].split('#')[0].replace(/\/{2,}/g, '/');

  if (!path || path === '/') {
    return '/';
  }

  return path.endsWith('/') ? path.slice(0, -1) : path;
}

/** The text itself, with markup taken out and the whitespace collapsed to single spaces. */
export function plainText(text: string | null | undefined): string {
  if (!text) {
    return '';
  }

  return text
    .replace(/<[^>]*>/g, ' ')
    .replace(/&nbsp;/gi, ' ')
    .replace(/&quot;/gi, '"')
    .replace(/&#39;|&apos;/gi, "'")
    .replace(/&lt;/gi, '<')
    .replace(/&gt;/gi, '>')
    .replace(/&amp;/gi, '&')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * The description a head carries: the page's own words, cut to the length a result shows and ending on a whole word
 * so the cut never lands mid-word. A description that is empty stays empty - the caller falls back to the shop's own.
 */
export function metaDescription(text: string | null | undefined): string {
  const clean = plainText(text);

  if (clean.length <= DESCRIPTION_LIMIT) {
    return clean;
  }

  const cut = clean.slice(0, DESCRIPTION_LIMIT - 1);

  // Cutting at the last space keeps a word whole; a single very long word (no space in reach) is cut where it stands
  // rather than thrown away.
  const lastSpace = cut.lastIndexOf(' ');
  const kept = lastSpace > DESCRIPTION_LIMIT / 2 ? cut.slice(0, lastSpace) : cut;

  return `${kept.replace(/[\s,;:.\-]+$/, '')}…`;
}

/**
 * The title a browser tab and a search result show: the page's own title, with the brand after it. A title that names
 * the brand already is left alone, so the home page is not written '... | Homecuties | Homecuties'.
 */
export function titleWithBrand(title: string): string {
  const clean = plainText(title);

  if (!clean) {
    return BRAND_NAME;
  }

  return clean.toLowerCase().includes(BRAND_NAME.toLowerCase()) ? clean : `${clean} | ${BRAND_NAME}`;
}

/** What a product is called: its title, or the name it is filed under when the shop left the title blank. */
export function productName(product: Product): string {
  return plainText(product.ProductTitle) || plainText(product.ProductName);
}

/** Every photograph of a product as an absolute url, in the order its page shows them (see ProductPicture). */
export function productImageUrls(product: Product): string[] {
  const pictures = (product.Pictures || []).map(picture => productImageUrl(picture.Large));
  const urls = pictures.length > 0 ? pictures : [productImageUrl(product.PromoImage)];

  return urls.filter(url => !!url).map(absoluteUrl);
}

/** The photograph a product's share card draws: the one its page opens on. */
export function productShareImage(product: Product): string | undefined {
  return productImageUrls(product)[0];
}

/** A product's own page: what its head says once the product has arrived. */
export function productMetadata(product: Product): PageMetadata {
  const name = productName(product);

  return {
    title: name || 'Handcrafted piece',
    description: metaDescription(product.ProductDescription) || `${name} — handcrafted home decor from ${BRAND_NAME}.`,
    path: `/product/${product.ProductID}`,
    image: productShareImage(product),
    imageAlt: name,
    type: 'product',
    keywords: [
      name,
      ...(product.Categories || []).map(category => category.CategoryName),
      ...(product.Features || []).map(feature => feature.Feature)
    ].filter(term => !!term)
  };
}

/**
 * The Product a search engine reads off a product page: what the piece is, what it costs and whether it can be
 * bought. Only what the page itself shows is written down - the price is the shop's own listing price (taxes and
 * charges inside it, see Product.ListingPrice), and a piece the shop has priced at nothing carries no offer rather
 * than an offer of zero, which would be a lie a result could repeat.
 */
export function productStructuredData(product: Product): Record<string, unknown> {
  const name = productName(product);
  const url = absoluteUrl(`/product/${product.ProductID}`);
  const images = productImageUrls(product);
  const description = plainText(product.ProductDescription);
  const category = (product.Categories || [])[0]?.CategoryName;

  const data: Record<string, unknown> = {
    '@context': 'https://schema.org',
    '@type': 'Product',
    name,
    url,
    brand: { '@type': 'Brand', name: BRAND_NAME }
  };

  if (description) {
    data['description'] = description;
  }
  if (images.length > 0) {
    data['image'] = images;
  }
  if (category) {
    data['category'] = category;
  }

  if (typeof product.ListingPrice === 'number' && product.ListingPrice > 0) {
    data['offers'] = {
      '@type': 'Offer',
      url,
      priceCurrency: 'INR',
      price: product.ListingPrice.toFixed(2),
      availability: product.IsInStock ? 'https://schema.org/InStock' : 'https://schema.org/OutOfStock',
      itemCondition: 'https://schema.org/NewCondition'
    };
  }

  return data;
}
